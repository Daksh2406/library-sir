/* ============================================================
   HELPER FUNCTIONS
   ============================================================ */

/**
 * Get current language from localStorage.
 * Default: 'en'
 */
function getCurrentLang() {
  return localStorage.getItem('sal_lang') || 'en';
}

/**
 * Set language and update html lang attribute.
 */
function setLanguage(lang) {
  if (!TRANSLATIONS[lang]) lang = 'en';
  localStorage.setItem('sal_lang', lang);
  document.documentElement.lang = lang;
}

/**
 * Translate a single key.
 * Fallback to English if key missing in current language.
 */
function t(key, lang) {
  lang = lang || getCurrentLang();
  return (TRANSLATIONS[lang] && TRANSLATIONS[lang][key])
      || TRANSLATIONS.en[key]
      || key;
}

/**
 * Apply translations to all elements with data-i18n attributes.
 * Also handles data-i18n-placeholder for inputs.
 */
function applyTranslations(lang) {
  lang = lang || getCurrentLang();

  // Text content
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key, lang);
    if (val !== undefined && val !== null) {
      el.textContent = val;
    }
  });

  // Placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const val = t(key, lang);
    if (val) el.setAttribute('placeholder', val);
  });

  // Update html lang
  document.documentElement.lang = lang;
}

/**
 * Toggle language between Hindi and English.
 * Returns the new language code.
 */
function toggleLanguage() {
  const current = getCurrentLang();
  const next = current === 'hi' ? 'en' : 'hi';
  setLanguage(next);
  applyTranslations(next);
  return next;
}

/**
 * Get the label to show on the language switch button.
 * Returns 'हिं' when current is Hindi, 'EN' when English.
 */
function getLangLabel() {
  return getCurrentLang() === 'hi' ? 'हिं' : 'EN';
}

/* ============================================================
   AUTO-APPLY ON PAGE LOAD
   ============================================================ */
document.addEventListener('DOMContentLoaded', () => {
  applyTranslations(getCurrentLang());
});

/* ============================================================
   AUTO-BIND LANGUAGE SWITCH BUTTON
   Har page pe `id="langSwitch"` wala button automatically
   bind ho jayega — har page mein manually code likhne ki
   zaroorat nahi.
   ============================================================ */
document.addEventListener('DOMContentLoaded', () => {
  const langSwitch = document.getElementById('langSwitch');
  const langLabel = document.getElementById('langLabel');

  if (langSwitch) {
    // Set initial label
    if (langLabel) {
      langLabel.textContent = getLangLabel();
    }

    // Bind click
    langSwitch.addEventListener('click', () => {
      const next = toggleLanguage();
      if (langLabel) {
        langLabel.textContent = next === 'hi' ? 'हिं' : 'EN';
      }
    });
  }
});